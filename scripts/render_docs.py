# --------------------------------------------------------------------------- helpers

def lit(g: Graph, node, prop, lang: str) -> str | None:
    for o in g.objects(node, prop):
        if isinstance(o, Literal) and o.language == lang:
            return str(o)
    return None


def en(g: Graph, node) -> str:
    return lit(g, node, SKOS.prefLabel, "en") or local(node)


def local(node) -> str:
    s = str(node)
    for prefix, ns in (("mbh:", MBH), ("mbhx:", MBHX), ("mb:", MB)):
        if s.startswith(str(ns)):
            return prefix + s[len(str(ns)):]
    return s


def name_of(node) -> str:
    return str(node).rsplit("/", 1)[-1].rsplit("#", 1)[-1]


def mermaid_id(node) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name_of(node))


def file_order(ttl_text: str) -> dict[str, int]:
    """Position of each mbh: subject in the Turtle file, so listings follow the author's order."""
    order: dict[str, int] = {}
    for m in re.finditer(r"^mbh:([A-Za-z0-9-]+)\s+a\s", ttl_text, re.M):
        order.setdefault(m.group(1), len(order))
    return order


def wikidata_links(g: Graph, node) -> str:
    out = []
    for prop, sign in ((SKOS.exactMatch, ""), (SKOS.closeMatch, "≈ ")):
        for o in g.objects(node, prop):
            if str(o).startswith(WD):
                qid = str(o)[len(WD):]
                out.append(f"{sign}[{qid}]({o})")
    return ", ".join(out)


def md_table(headers: list[str], rows: list[list[str]]) -> str:
    esc = lambda s: str(s).replace("|", "\\|")
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(esc(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def characters_below(g: Graph, grouping, memo: dict) -> set:
    if grouping in memo:
        return memo[grouping]
    found = set()
    for n in g.subjects(SKOS.broader, grouping):
        if (n, RDF.type, MBHX.Character) in g:
            found.add(n)
        else:
            found |= characters_below(g, n, memo)
    memo[grouping] = found
    return found


# --------------------------------------------------------------------------- README blocks

def stats_block(g: Graph) -> str:
    chars = set(g.subjects(RDF.type, MBHX.Character))
    groups = set(g.subjects(RDF.type, MBHX.Grouping))
    ordered = set(g.subjects(RDF.type, SKOS.OrderedCollection))
    colls = set(g.subjects(RDF.type, SKOS.Collection)) | ordered
    tops = list(g.objects(SCHEME, SKOS.hasTopConcept))
    pref = Counter(o.language for o in g.objects(None, SKOS.prefLabel))
    alt = sum(1 for _ in g.triples((None, SKOS.altLabel, None)))
    hidden = sum(1 for _ in g.triples((None, SKOS.hiddenLabel, None)))
    rel_props = list(g.subjects(RDFS.subPropertyOf, MBHX.characterRelation))
    rels = sum(sum(1 for _ in g.triples((None, p, None))) for p in rel_props)
    rel_used = sum(1 for p in rel_props if any(True for _ in g.triples((None, p, None))))
    war = set(g.subjects(MBHX.fellOnWarDay, None))
    poly = {c for c in chars if sum(1 for _ in g.objects(c, SKOS.broader)) > 1}
    wd_mapped = {c for c in chars
                 if any(str(o).startswith(WD) for p in (SKOS.exactMatch, SKOS.closeMatch) for o in g.objects(c, p))}
    wp = {c for c in chars if any(True for _ in g.objects(c, FOAF.isPrimaryTopicOf))}
    unmapped = sorted(en(g, c) for c in chars - wd_mapped)

    rows = [
        ["Triples", f"{len(g):,}"],
        ["Characters (`mbhx:Character`)", f"{len(chars)}"],
        ["Groupings (`mbhx:Grouping`)", f"{len(groups)}, of which {len(tops)} top concepts"],
        ["Collections", f"{len(colls)}, of which {len(ordered)} ordered"],
        ["Preferred labels", f"{sum(pref.values())} (en {pref.get('en', 0)} · sa-Deva {pref.get('sa-Deva', 0)} · sa-Latn {pref.get('sa-Latn', 0)})"],
        ["Alternative labels (epithets, patronymics, names in disguise)", f"{alt}"],
        ["Hidden labels (spelling variants)", f"{hidden}"],
        ["Relations between characters", f"{rels} statements over {rel_used} properties"],
        ["Characters with a day of the war on which they fell", f"{len(war)}"],
        ["Characters under more than one grouping", f"{len(poly)}"],
        ["Characters mapped to Wikidata", f"{len(wd_mapped)} of {len(chars)}"],
        ["Characters linked to their Wikipedia article", f"{len(wp)} of {len(chars)}"],
    ]
    text = md_table(["Measure", "Value"], rows)
    if unmapped:
        text += ("\n\nCharacters without a Wikidata item of their own, linked to the Wikipedia list article instead: "
                 + ", ".join(unmapped) + ".")
    return text


def top_concepts_block(g: Graph, order: dict[str, int]) -> str:
    memo: dict = {}
    rows = []
    tops = sorted(g.objects(SCHEME, SKOS.hasTopConcept), key=lambda n: order.get(name_of(n), 10**6))
    total = 0
    for t in tops:
        n = len(characters_below(g, t, memo))
        total += n
        sa = lit(g, t, SKOS.prefLabel, "sa-Latn") or ""
        rows.append([f"**{en(g, t)}**", sa, lit(g, t, SKOS.definition, "en") or "", str(n)])
    chars = len(set(g.subjects(RDF.type, MBHX.Character)))
    text = md_table(["Top concept", "Sanskrit", "Covers", "Characters"], rows)
    text += (f"\n\nThe character column sums to {total} for {chars} characters because "
             f"{total - chars} placements are second placements of characters that belong to two groupings.")
    return text


def groupings_outline(g: Graph, order: dict[str, int]) -> str:
    memo: dict = {}
    key = lambda n: order.get(name_of(n), 10**6)
    lines = []

    def walk(node, depth):
        n = len(characters_below(g, node, memo))
        sa = lit(g, node, SKOS.prefLabel, "sa-Latn")
        sa_txt = f" · {sa}" if sa else ""
        lines.append(f"{'  ' * depth}- {en(g, node)}{sa_txt} ({n})")
        for child in sorted(g.subjects(SKOS.broader, node), key=key):
            if (child, RDF.type, MBHX.Grouping) in g:
                walk(child, depth + 1)

    for t in sorted(g.objects(SCHEME, SKOS.hasTopConcept), key=key):
        walk(t, 0)
    return "\n".join(lines)


def relations_block(g: Graph) -> str:
    rows = []
    for p in g.subjects(RDFS.subPropertyOf, MBHX.characterRelation):
        n = sum(1 for _ in g.triples((None, p, None)))
        if n == 0:
            continue
        if (p, RDF.type, OWL.SymmetricProperty) in g:
            inverse = "symmetric"
        else:
            inv = g.value(p, OWL.inverseOf)
            inverse = f"`{local(inv)}`" if inv else ""
        rows.append((n, f"`{local(p)}`", inverse, lit(g, p, SKOS.definition, "en") or ""))
    rows.sort(key=lambda r: (-r[0], r[1]))
    return md_table(["Property", "Inverse", "Stated", "Meaning"],
                    [[r[1], r[2], str(r[0]), r[3]] for r in rows])


def collections_block(g: Graph, order: dict[str, int]) -> str:
    ordered = set(g.subjects(RDF.type, SKOS.OrderedCollection))
    colls = set(g.subjects(RDF.type, SKOS.Collection)) | ordered
    rows = []
    for c in sorted(colls, key=lambda n: order.get(name_of(n), 10**6)):
        members = sum(1 for _ in g.objects(c, SKOS.member))
        kind = "ordered" if c in ordered else ""
        rows.append([f"`{local(c)}`", en(g, c), kind, str(members)])
    return md_table(["Collection", "Label", "Kind", "Members"], rows)


def mermaid_tree(g: Graph, nodes: set, with_foster: bool) -> str:
    deities = characters_below(g, MBH["deities"], {})
    lines = ["flowchart TB",
             "    classDef deity fill:#fff3bf,stroke:#b08900,color:#1a1a1a"]
    for n in sorted(nodes, key=lambda x: en(g, x)):
        label = en(g, n).replace('"', "'")
        cls = ":::deity" if n in deities else ""
        lines.append(f'    {mermaid_id(n)}["{label}"]{cls}')
    edges = []
    for child, parent in g.subject_objects(MBHX.childOf):
        if child in nodes and parent in nodes:
            edges.append(f"    {mermaid_id(parent)} --> {mermaid_id(child)}")
    if with_foster:
        for child, parent in g.subject_objects(MBHX.fosterChildOf):
            if child in nodes and parent in nodes:
                edges.append(f"    {mermaid_id(parent)} -. foster .-> {mermaid_id(child)}")
    lines += sorted(edges)
    return "```mermaid\n" + "\n".join(lines) + "\n```"


def compact_tree_block(g: Graph) -> str:
    nodes = {MBH[n] for n in MAIN_LINE}
    missing = [n for n in MAIN_LINE if (MBH[n], RDF.type, MBHX.Character) not in g]
    if missing:
        raise SystemExit(f"MAIN_LINE names characters that are not in the data: {missing}")
    return mermaid_tree(g, nodes, with_foster=False)


# --------------------------------------------------------------------------- docs/ files

def hierarchy_md(g: Graph, order: dict[str, int]) -> str:
    key = lambda n: order.get(name_of(n), 10**6)
    memo: dict = {}
    lines = ["# The hierarchy", "", GENERATED, "",
             "Every concept of the scheme in its place under `skos:broader`. Groupings are in bold with the "
             "number of characters below them; characters show their Devanagari and IAST labels and their "
             "Wikidata item (≈ marks a `skos:closeMatch`). A character that belongs to two groupings is listed "
             "under both, with a pointer to the other.", ""]

    def character_line(c, here, depth):
        sa_deva = lit(g, c, SKOS.prefLabel, "sa-Deva") or ""
        sa_latn = lit(g, c, SKOS.prefLabel, "sa-Latn") or ""
        bits = [en(g, c)]
        if sa_deva or sa_latn:
            bits.append(" · ".join(b for b in (sa_deva, sa_latn) if b))
        wd = wikidata_links(g, c)
        if wd:
            bits.append(wd)
        others = [en(g, o) for o in g.objects(c, SKOS.broader) if o != here]
        if others:
            bits.append("also under " + "; ".join(sorted(others)))
        lines.append(f"{'  ' * depth}- {' — '.join(bits)}")

    def walk(node, depth):
        n = len(characters_below(g, node, memo))
        sa = lit(g, node, SKOS.prefLabel, "sa-Latn")
        sa_txt = f" · {sa}" if sa else ""
        wd = wikidata_links(g, node)
        wd_txt = f" — {wd}" if wd else ""
        lines.append(f"{'  ' * depth}- **{en(g, node)}**{sa_txt} ({n}){wd_txt}")
        children = sorted(g.subjects(SKOS.broader, node), key=key)
        for child in children:
            if (child, RDF.type, MBHX.Grouping) in g:
                walk(child, depth + 1)
        for child in children:
            if (child, RDF.type, MBHX.Character) in g:
                character_line(child, node, depth + 1)

    for t in sorted(g.objects(SCHEME, SKOS.hasTopConcept), key=key):
        walk(t, 0)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def family_tree_md(g: Graph) -> str:
    nodes = set()
    for prop in (MBHX.childOf, MBHX.fosterChildOf):
        for s, o in g.subject_objects(prop):
            nodes.add(s)
            nodes.add(o)
    n_child = sum(1 for _ in g.triples((None, MBHX.childOf, None)))
    n_foster = sum(1 for _ in g.triples((None, MBHX.fosterChildOf, None)))
    return "\n".join([
        "# The family tree", "", GENERATED, "",
        f"Every `mbhx:childOf` statement in the data ({n_child}) drawn as an arrow from parent to child, "
        f"and every `mbhx:fosterChildOf` ({n_foster}) as a dashed arrow. Deities are shaded. "
        "Two fathers for one child reflect the epic itself: fatherhood by niyoga (Vyasa and Vichitravirya; "
        "Pandu and the gods Kunti and Madri invoked) is recorded beside birth. Marriages are not drawn; "
        "they are `mbhx:spouseOf` in the data.", "",
        mermaid_tree(g, nodes, with_foster=True), "",
    ])


def run_query(g: Graph, body: str) -> tuple[list[str], list[list[str]]]:
    res = g.query(PREFIXES + body)
    headers = [str(v) for v in res.vars]
    rows = []
    for row in res:
        bound = row.asdict()
        cells = []
        for v in res.vars:
            val = bound.get(str(v))
            if val is None:
                cells.append("")
            elif isinstance(val, URIRef) and str(val).startswith(WD):
                cells.append(f"[{str(val)[len(WD):]}]({val})")
            elif isinstance(val, URIRef):
                cells.append(f"`{local(val)}`")
            else:
                cells.append(str(val))
        rows.append(cells)
    return headers, rows


def queries_md(g: Graph) -> str:
    lines = ["# SPARQL cookbook", "", GENERATED, "",
             "Each query below was run against `mahabharata_characters.ttl` with rdflib when this page was "
             "generated, and the result shown is what it returned. The queries use these prefixes:", "",
             "```sparql", PREFIXES.rstrip(), "```", "",
             "Run one with rdflib (`Graph().parse('mahabharata_characters.ttl').query(q)`) or with Apache Jena "
             "(`arq --data=mahabharata_characters.ttl --query=q.rq`). No inference is needed for any of them; "
             "where the inverse of a relation is wanted, the query uses an inverse property path instead.", ""]
    for i, (title, explanation, body) in enumerate(QUERIES, 1):
        headers, rows = run_query(g, body)
        lines += [f"## {i}. {title}", "", explanation, "", "```sparql", body, "```", ""]
        if not rows:
            lines.append("_No results._")
        elif len(headers) == 1:
            lines.append(f"{len(rows)} result{'s' if len(rows) != 1 else ''}: "
                         + ", ".join(r[0] for r in rows) + ".")
        else:
            lines.append(md_table(headers, rows))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# --------------------------------------------------------------------------- assembly

def replace_block(text: str, name: str, body: str) -> str:
    start, end = f"<!-- {name}:start -->", f"<!-- {name}:end -->"
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
    if not pattern.search(text):
        raise SystemExit(f"README.md has no <!-- {name}:start --> / <!-- {name}:end --> markers")
    return pattern.sub(lambda _m: f"{start}\n{GENERATED}\n{body.strip()}\n{end}", text)


def render(g: Graph, order: dict[str, int]) -> dict[Path, str]:
    readme = README.read_text(encoding="utf-8")
    readme = replace_block(readme, "stats", stats_block(g))
    readme = replace_block(readme, "top-concepts", top_concepts_block(g, order))
    readme = replace_block(readme, "groupings", groupings_outline(g, order))
    readme = replace_block(readme, "relations", relations_block(g))
    readme = replace_block(readme, "collections", collections_block(g, order))
    readme = replace_block(readme, "family-tree", compact_tree_block(g))
    return {
        README: readme,
        DOCS / "hierarchy.md": hierarchy_md(g, order),
        DOCS / "family-tree.md": family_tree_md(g),
        DOCS / "queries.md": queries_md(g),
    }


def main(argv: list[str]) -> int:
    check = "--check" in argv
    ttl_text = TTL.read_text(encoding="utf-8")
    g = Graph()
    g.parse(TTL, format="turtle")
    outputs = render(g, file_order(ttl_text))
    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    rel = lambda p: p.relative_to(ROOT)
    if check:
        if stale:
            print("Generated documentation is out of date:", ", ".join(str(rel(p)) for p in stale))
            print("Run: python scripts/render_docs.py")
            return 1
        print("Generated documentation is up to date.")
        return 0
    if stale:
        print("Wrote:", ", ".join(str(rel(p)) for p in stale))
    else:
        print("Nothing changed.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
