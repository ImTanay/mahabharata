#!/usr/bin/env python3
"""Render the documentation of the concept scheme from the data itself.

Writes
  docs/hierarchy.md     the full SKOS hierarchy with labels and mappings
  docs/family-tree.md   every stated parent-child link as a Mermaid diagram
  docs/queries.md       a SPARQL cookbook with the results each query returns
and refreshes the generated blocks in README.md, which sit between
<!-- name:start --> and <!-- name:end --> markers.

Usage:
  python scripts/render_docs.py          write the files
  python scripts/render_docs.py --check  exit 1 if any file would change (used in CI)

Everything here is derived from mahabharata_characters.ttl, so a count or a
diagram in the documentation can never disagree with the data.
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

from rdflib import Graph, Literal, Namespace, RDF, RDFS, URIRef
from rdflib.namespace import FOAF, OWL, SKOS

ROOT = Path(__file__).resolve().parents[1]
TTL = ROOT / "mahabharata_characters.ttl"
DOCS = ROOT / "docs"
README = ROOT / "README.md"

